//! Single binary for every GitImage workload (design D1).

use std::path::PathBuf;

use anyhow::Context;
use clap::{Parser, Subcommand, ValueEnum};
use kube::CustomResourceExt;

#[derive(Parser)]
#[command(
    name = "gitimage",
    version,
    about = "Git URL to running pod, built in-cluster"
)]
struct Cli {
    /// `json` in clusters, `text` for local development.
    #[arg(
        long,
        global = true,
        env = "GITIMAGE_LOG_FORMAT",
        default_value = "json"
    )]
    log_format: LogFormat,
    /// An EnvFilter string.
    #[arg(
        long,
        global = true,
        env = "GITIMAGE_LOG_LEVEL",
        default_value = "info,kube=warn"
    )]
    log_level: String,
    #[command(subcommand)]
    command: Command,
}

#[derive(Clone, Copy, ValueEnum)]
enum LogFormat {
    Json,
    Text,
}

#[derive(Subcommand)]
enum Command {
    /// Reconcilers, push endpoint, hooks receiver.
    Controller,
    /// Mutating admission webhook.
    Webhook,
    /// Read-only OCI server on 127.0.0.1 for s3 storage mode.
    Node,
    /// Init container of a build Job: fetch one commit and check it out.
    Clone,
    /// Print the CRD YAML (or write it to --out).
    Crdgen {
        #[arg(long)]
        out: Option<PathBuf>,
    },
    /// Print the version.
    Version,
}

fn init_logging(format: LogFormat, level: &str) -> anyhow::Result<()> {
    let filter = tracing_subscriber::EnvFilter::try_new(level).context("--log-level")?;
    let builder = tracing_subscriber::fmt()
        .with_env_filter(filter)
        .with_writer(std::io::stderr);
    match format {
        LogFormat::Json => builder
            .json()
            .flatten_event(true)
            .with_current_span(true)
            .init(),
        LogFormat::Text => builder.init(),
    }
    Ok(())
}

fn crd_yaml() -> anyhow::Result<String> {
    let crd = gitimage_api::GitImage::crd();
    Ok(format!(
        "# Generated by `gitimage crdgen`. Do not edit.\n---\n{}",
        serde_yaml::to_string(&crd)?
    ))
}

#[tokio::main]
async fn main() -> anyhow::Result<()> {
    let cli = Cli::parse();
    match cli.command {
        Command::Crdgen { out } => {
            let yaml = crd_yaml()?;
            match out {
                Some(path) => std::fs::write(&path, yaml)
                    .with_context(|| format!("writing {}", path.display()))?,
                None => print!("{yaml}"),
            }
            return Ok(());
        }
        Command::Version => {
            println!("gitimage {}", env!("CARGO_PKG_VERSION"));
            return Ok(());
        }
        _ => {}
    }
    init_logging(cli.log_format, &cli.log_level)?;
    let name = match cli.command {
        Command::Controller => "controller",
        Command::Webhook => "webhook",
        Command::Node => "node",
        Command::Clone => "clone",
        Command::Crdgen { .. } | Command::Version => unreachable!(),
    };
    tracing::error!(subcommand = name, "not implemented yet");
    std::process::exit(2)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn crd_is_namespaced_with_status_subresource() {
        let yaml = crd_yaml().unwrap();
        assert!(yaml.contains("name: gitimages.gitimage.dev"));
        assert!(yaml.contains("scope: Namespaced"));
        assert!(yaml.contains("status: {}"));
    }

    #[test]
    fn checked_in_crd_matches_generated() {
        let path = concat!(
            env!("CARGO_MANIFEST_DIR"),
            "/../../charts/gitimage/crds/gitimage.yaml"
        );
        let on_disk = std::fs::read_to_string(path).unwrap_or_default();
        assert_eq!(
            on_disk,
            crd_yaml().unwrap(),
            "CRD drift: run `cargo run -p gitimage -- crdgen --out charts/gitimage/crds/gitimage.yaml`"
        );
    }
}
